import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createLayout } from '../src/catalog.js';
import { setup, provider, waitFor, send, close } from './fixtures/relay-server.mjs';

test('all ready starts another round on the same sockets and resets combat, results, votes and scores', async t => {
  const auth = await provider(t, { holdResults: true });
  const { join } = await setup(t, { ...auth.env, ALLOW_DEV_GUESTS: 'false' }, { tickMs: 5 });
  const first = await join({ roomId: 'repeat', accessToken: 'first', mapId: 'lagoon', characterId: 'nori', skinId: 'mint', itemMode: true });
  const second = await join({ roomId: 'repeat', accessToken: 'second', characterId: 'bibi', skinId: 'sunset' });
  const originalIds = first.state.players.map(p => p.id);
  send(first, 'rematch');
  send(first, 'input', { action: 'place_orb' });
  await waitFor(() => first.state.phase === 'finished');
  const old = structuredClone(first.state);
  assert.equal(old.round, 0);
  assert.ok(old.players.some(p => !p.alive));
  await waitFor(() => auth.requests.some(r => r.path === '/rest/v1/rpc/record_match'));
  const oldSave = structuredClone(auth.requests.find(r => r.path === '/rest/v1/rpc/record_match').body);
  send(first, 'rematch'); send(first, 'rematch');
  await waitFor(() => first.state.rematch?.readyPlayerIds.length === 1);
  assert.equal(first.state.phase, 'finished');
  assert.deepEqual(first.state.rematch, { readyPlayerIds: [first.playerId], total: 2 });
  send(second, 'rematch');
  await waitFor(() => first.messages.some(m => m.type === 'state' && m.round === 1));
  const reset = first.messages.find(m => m.type === 'state' && m.round === 1);
  assert.equal(reset.phase, 'playing');
  assert.equal(reset.tick, 0);
  assert.equal(reset.remaining, 1200);
  assert.notEqual(reset.matchId, old.matchId);
  assert.deepEqual(reset.players.map(p => p.id), originalIds);
  assert.equal(reset.roomId, old.roomId);
  assert.equal(reset.mapId, 'lagoon');
  assert.equal(reset.itemMode, true);
  assert.deepEqual(reset.rematch, { readyPlayerIds: [], total: 2 });
  assert.equal(reset.result, null);
  assert.equal(reset.relay, null);
  assert.deepEqual(reset.items, []);
  assert.deepEqual(reset.orbs, []);
  assert.deepEqual(reset.waves, []);
  assert.deepEqual(reset.dartEffects, []);
  assert.deepEqual(new Set(reset.soft), createLayout('lagoon', 'duel').soft);
  for (const p of reset.players) {
    assert.equal(p.alive, true);
    for (const field of ['bubbleTicks', 'score', 'bombsPlaced', 'itemsCollected', 'rescues', 'deliveries', 'respawnTicks', 'speedLevel', 'darts']) assert.equal(p[field], 0, field);
    assert.equal(p.maxOrbs, 1); assert.equal(p.range, 3); assert.equal(p.dash, false); assert.equal(p.pin, false);
  }
  assert.deepEqual(reset.players.map(p => [p.characterId, p.skinId]), [['nori', 'mint'], ['bibi', 'sunset']]);
  send(second, 'input', { action: 'place_orb' });
  await waitFor(() => first.state.phase === 'finished' && first.state.round === 1);
  await waitFor(() => auth.requests.filter(r => r.path === '/rest/v1/rpc/record_match').length === 2);
  const saves = auth.requests.filter(r => r.path === '/rest/v1/rpc/record_match').map(r => r.body);
  assert.deepEqual(saves[0], oldSave);
  assert.notEqual(saves[0].p_match_id, saves[1].p_match_id);
  assert.equal(first.state.result.scoreboard.find(p => p.id === first.playerId).score, 200);
  auth.release();
});

test('partial rematch waits for a replacement, retains the survivor spawn, and snapshots a fresh roster', async t => {
  const { join } = await setup(t, {}, { tickMs: 5 });
  const first = await join({ roomId: 'refill' });
  const second = await join({ roomId: 'refill', characterId: 'toto', skinId: 'mint' });
  await waitFor(() => second.state.phase === 'playing');
  const oldMatchId = second.state.matchId;
  await close(first);
  await waitFor(() => second.state.phase === 'finished');
  send(second, 'rematch');
  await waitFor(() => second.state.phase === 'waiting');
  assert.equal(second.state.round, 1);
  assert.equal(second.state.matchId, null);
  assert.equal(second.state.result, null);
  assert.deepEqual(second.state.players.map(p => [p.id, p.x, p.y]), [[second.playerId, 11, 9]]);
  send(second, 'rematch');
  const replacement = await join({ roomId: 'refill' });
  await waitFor(() => second.state.phase === 'playing');
  assert.notEqual(second.state.matchId, oldMatchId);
  assert.deepEqual(second.state.rematch, { readyPlayerIds: [], total: 2 });
  assert.deepEqual(second.state.players.find(p => p.id === replacement.playerId).x, 1);
  send(replacement, 'input', { action: 'place_orb' });
  await waitFor(() => second.state.phase === 'finished');
  assert.deepEqual(new Set(second.state.result.scoreboard.map(p => p.id)), new Set([second.playerId, replacement.playerId]));
});

test('departure rechecks ready votes and a replacement inherits the missing team slot and relay rules', async t => {
  const { join } = await setup(t, {}, { tickMs: 1 });
  const clients = [];
  for (let i = 0; i < 8; i++) clients.push(await join({ roomId: 'team-repeat', mode: 'team', ruleSet: 'relay', itemMode: false }));
  await waitFor(() => clients[0].state.phase === 'finished');
  assert.equal(clients[0].state.result.reason, 'relay_time');
  const before = clients[0].state;
  const departing = clients[7], missing = before.players.find(p => p.id === departing.playerId);
  for (const client of clients.slice(0, 7)) send(client, 'rematch');
  await waitFor(() => clients[0].state.rematch?.readyPlayerIds.length === 7);
  await close(departing);
  await waitFor(() => clients[0].state.phase === 'waiting');
  const waiting = clients[0].state;
  assert.equal(waiting.round, 1);
  assert.equal(waiting.matchId, null);
  assert.deepEqual(waiting.relay.scores, { blue: 0, pink: 0 });
  assert.deepEqual(waiting.relay.star, { x: 6, y: 5 });
  assert.deepEqual(waiting.rematch, { readyPlayerIds: [], total: 7 });
  assert.deepEqual(waiting.players.map(p => [p.id, p.team]), before.players.filter(p => p.id !== departing.playerId).map(p => [p.id, p.team]));
  const replacement = await join({ roomId: 'team-repeat', mode: 'team' });
  const replacementPlayer = replacement.state.players.find(p => p.id === replacement.playerId);
  assert.equal(replacement.state.phase, 'playing');
  assert.equal(replacement.state.ruleSet, 'relay');
  assert.notEqual(replacement.state.matchId, before.matchId);
  assert.equal(replacementPlayer.team, missing.team);
  assert.deepEqual([replacementPlayer.x, replacementPlayer.y], [missing.x, missing.y]);
});
