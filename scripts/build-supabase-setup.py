"""Generate the atomic Supabase SQL Editor install from canonical migrations."""
import argparse
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
SOURCES = (
    'Supabase/schema.sql',
    'Supabase/migrations/20261102_team_match_history.sql',
    'Supabase/migrations/20261102_rankings.sql',
    'Supabase/migrations/20261106_team_elo.sql',
    'Supabase/migrations/20261107_member_accounts.sql',
)
TARGET = ROOT / 'Supabase/setup.sql'


def body_without_transaction(source):
    """Remove only the known migration's outer transaction, never PL/pgSQL blocks."""
    lines = (ROOT / source).read_text().splitlines()
    statements = [index for index, line in enumerate(lines)
                  if line.strip() and not line.lstrip().startswith('--')]
    if source != 'Supabase/schema.sql':
        first, last = statements[0], statements[-1]
        if lines[first].strip().lower() != 'begin;' or lines[last].strip().lower() != 'commit;':
            raise ValueError(f'{source}: expected one outer BEGIN/COMMIT wrapper')
        del lines[last]
        del lines[first]
    return '\n'.join(lines).strip()


def build():
    sections = [
        '-- Generated by python3 scripts/build-supabase-setup.py. Do not edit directly.',
        '-- Paste this ENTIRE file into the Supabase SQL Editor and run as postgres.',
        '-- Fresh installation or upgrade: preserves existing accounts, ratings and records.',
        '-- One transaction: any error rolls back the complete setup. Safe to run again.',
        'begin;',
        "set local lock_timeout = '10s';",
        "set local statement_timeout = '120s';",
    ]
    for source in SOURCES:
        sections.extend(['', f'-- Source: {source}', body_without_transaction(source)])
    sections.extend(['', "notify pgrst, 'reload schema';", 'commit;', '',
                     "select 'Database setup complete' as status;", ''])
    return '\n'.join(sections)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if the checked-in SQL is missing or outdated')
    args = parser.parse_args()
    generated = build()
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != generated:
            print('Supabase/setup.sql is outdated; run python3 scripts/build-supabase-setup.py', file=sys.stderr)
            return 1
        print('PASS: Supabase/setup.sql matches all canonical migrations')
    else:
        TARGET.write_text(generated)
        print('Generated Supabase/setup.sql')
    return 0


if __name__ == '__main__':
    sys.exit(main())
